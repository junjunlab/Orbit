const fs = require('fs');
const { connect } = require('C:/Users/JunJun/Desktop/agent_devop_pkgs/igv/igv_0.3/tools/cdp');
const sleep = (ms) => new Promise((r) => setTimeout(r, ms));
const URL_ = 'http://127.0.0.1:8799/?db=hg38&locus=chr1:55,000,000-62,000,000';
const OUT = 'C:/Users/JunJun/Desktop/agent_devop_pkgs/igv/igv_0.4/tools/';
(async () => {
  const cdp = await connect();
  await cdp.send('Page.enable'); await cdp.send('Runtime.enable');
  await cdp.send('Emulation.setDeviceMetricsOverride', { width: 1440, height: 900, deviceScaleFactor: 1.5, mobile: false });
  const ev = async (expr) => {
    const r = await cdp.send('Runtime.evaluate', { expression: expr, returnByValue: true, awaitPromise: true });
    if (r.result && r.result.exceptionDetails) return { ERR: JSON.stringify(r.result.exceptionDetails).slice(0, 300) };
    return r.result && r.result.result ? r.result.result.value : undefined;
  };
  await cdp.send('Page.navigate', { url: URL_ });
  for (let i = 0; i < 120 && !(await ev('!!window.__igv')); i++) await sleep(150);
  await ev(`localStorage.setItem('orbit.lang','en')`);
  await cdp.send('Page.navigate', { url: URL_ });
  for (let i = 0; i < 120 && !(await ev('!!window.__igv')); i++) await sleep(150);
  await sleep(2500);
  const tid = await ev(`(() => { const t = (window.__igv.S.bw.list||[]).filter(x=>x.heatmap).pop(); return t ? t.id : null; })()`);
  await ev(`(() => { const S=window.__igv.S; S.bw.on['${tid}']=true; S.bw.cfg['${tid}']=Object.assign({}, S.bw.cfg['${tid}'],{segLayout:'row', segHide:[3,6]}); window.__igv.loadBwTracks && window.__igv.loadBwTracks(); })()`);
  await sleep(2500);
  console.log('sidebar:', await ev(`document.querySelector('.bw-trk .nm').textContent`));
  console.log('sub:', await ev(`document.querySelector('.track[data-bw="${tid}"] .sub').textContent`));
  await ev(`document.querySelector('.track[data-bw="${tid}"] .tgear').click()`);
  await sleep(700);
  console.log('head:', await ev(`document.querySelector('.tpop .smp-head').textContent`));
  console.log('hint:', await ev(`document.querySelector('.tpop .hint').textContent`));
  const s = await cdp.send('Page.captureScreenshot', { format: 'png' });
  fs.writeFileSync(OUT + '_seg_pick_en.png', Buffer.from(s.result.data, 'base64'));
  // 全不选后的空提示
  await ev(`(() => { const b=[...document.querySelectorAll('.tpop .smp-head .btn')].find(x=>x.textContent.trim()==='None'); b.click(); })()`);
  await sleep(900);
  await ev(`document.querySelector('#tpop .foot .btn.pri').click()`);
  await sleep(800);
  console.log('empty msg:', await ev(`(() => { const c = document.querySelector('.track[data-bw="${tid}"] canvas'); return c.width + 'x' + c.height; })()`));
  await ev(`localStorage.setItem('orbit.lang','zh')`);
  cdp.close();
})().catch((e) => { console.error(e); process.exit(1); });
